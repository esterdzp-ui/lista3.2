# EXERCÍCIO 11: Verificação de Vida
# Enunciado: Escreva um código que peça a vida atual do herói e use o operador == para imprimir True se a vida for igual a 0

# ENTRADA
vida_heroi = int(input("Digite a vida atual do herói: "))

# PROCESSAMENTO + SAÍDA
resultado = vida_heroi == 0
print(resultado)
