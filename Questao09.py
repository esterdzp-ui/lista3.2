# EXERCÍCIO 9: Dano de Combate
# Enunciado: Crie um script onde o dano_arma = 25 e a armadura_inimigo = 10. Calcule e mostre o dano real sofrido (dano menos armadura)

# ENTRADA / VARIÁVEIS
dano_arma = 25
armadura_inimigo = 10

# PROCESSAMENTO
dano_real = dano_arma - armadura_inimigo

# SAÍDA
print(f"Dano real sofrido pelo inimigo: {dano_real}")

