# EXERCÍCIO 18: Atualização de Posição
# Enunciado: No Godot 2D, a posição x aumenta quando o jogador vai para a direita.
# Se posicao_x = 10, escreva o código que usa o operador de atribuição para somar 5 a essa posição.

# ENTRADA
posicao_x = 10

# PROCESSAMENTO (operador +=)
posicao_x += 5

# SAÍDA
print(f"Nova posição X: {posicao_x}")
