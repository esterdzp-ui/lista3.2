# EXERCÍCIO 15: Média de XP
# Enunciado: Um jogador ganhou 100, 150 e 200 de XP em três batalhas.
# Escreva o código que calcula a média aritmética desses valores. (Lembre‑se dos parênteses!)

# ENTRADA
xp1 = 100
xp2 = 150
xp3 = 200

# PROCESSAMENTO
media_xp = (xp1 + xp2 + xp3) / 3

# SAÍDA
print(f"Média de XP: {media_xp}")

