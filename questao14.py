# EXERCÍCIO 14: Multiplicador de Poder
# Enunciado: Se o jogador pegar um Power‑Up que triplica o seu ataque, qual operador usar para atualizar a variável ataque = 15? Escreva o código

# VARIÁVEL
ataque = 15

# PROCESSAMENTO (multiplicação * )
ataque = ataque * 3

# SAÍDA
print(f"Ataque depois do Power‑Up: {ataque}")
